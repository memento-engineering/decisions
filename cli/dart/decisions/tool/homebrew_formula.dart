import 'dart:io';

/// The released binary targets, as `<os>-<arch>` asset suffixes.
const releaseTargets = ['macos-arm64', 'linux-x64', 'linux-arm64'];

/// Renders the `decisions` Homebrew formula for [version] from the contents
/// of a release's `SHA256SUMS` file.
///
/// Throws a [FormatException] when [sha256sums] lacks a target's asset, so a
/// partial release never reaches the tap.
String renderFormula({required String version, required String sha256sums}) {
  final sums = <String, String>{
    for (final line in sha256sums.split('\n'))
      if (line.trim().isNotEmpty)
        line.split(RegExp(r'\s+\*?')).last: line.split(RegExp(r'\s+')).first,
  };
  String sha(String target) {
    final asset = 'decisions-$version-$target';
    return sums[asset] ??
        (throw FormatException('SHA256SUMS has no entry for $asset'));
  }

  const base =
      'https://github.com/memento-engineering/decisions/releases/download';
  String url(String target) =>
      '$base/decisions-v#{version}/decisions-#{version}-$target';

  return '''
# Generated by memento-engineering/decisions
# (cli/dart/decisions/tool/homebrew_formula.dart) on each stable release.
# Do not edit by hand: the next release overwrites it.
class Decisions < Formula
  desc "Lint, index and search a decision register"
  homepage "https://github.com/memento-engineering/decisions"
  version "$version"
  license "MIT"

  on_macos do
    depends_on arch: :arm64

    url "${url('macos-arm64')}"
    sha256 "${sha('macos-arm64')}"
  end

  on_linux do
    on_intel do
      url "${url('linux-x64')}"
      sha256 "${sha('linux-x64')}"
    end

    on_arm do
      url "${url('linux-arm64')}"
      sha256 "${sha('linux-arm64')}"
    end
  end

  def install
    binary = Dir["decisions-*"].first
    chmod 0555, binary
    bin.install binary => "decisions"
  end

  test do
    assert_match "decisions #{version} ", shell_output("#{bin}/decisions --version")
  end
end
''';
}

/// Usage: `dart run tool/homebrew_formula.dart <version> <SHA256SUMS path>`.
void main(List<String> args) {
  if (args.length != 2) {
    stderr.writeln(
      'usage: dart run tool/homebrew_formula.dart <version> <SHA256SUMS>',
    );
    exitCode = 64;
    return;
  }
  stdout.write(
    renderFormula(
      version: args[0],
      sha256sums: File(args[1]).readAsStringSync(),
    ),
  );
}
