import 'dart:io';

import 'package:path/path.dart' as p;
import 'package:yaml/yaml.dart';

/// The canonical skills directory, relative to the package root.
const skillsDirectory = '../../../skills';

/// The generated library, relative to the package root.
const guidesFile = 'lib/src/guides.g.dart';

/// Renders `lib/src/guides.g.dart` from the canonical skills, or with
/// `--check` exits 1 when the committed file is stale.
///
/// Run from the package root: `dart run tool/generate_guides.dart`.
void main(List<String> arguments) {
  final check = arguments.contains('--check');
  final rendered = renderGuides(readSkills(skillsDirectory));
  final target = File(guidesFile);
  if (check) {
    final current = target.existsSync() ? target.readAsStringSync() : '';
    if (current != rendered) {
      stderr.writeln(
        '$guidesFile is stale; run dart run tool/generate_guides.dart',
      );
      exitCode = 1;
    }
    return;
  }
  target.writeAsStringSync(rendered);
}

/// Reads every `<directory>/<name>/SKILL.md`, keyed by skill directory name.
Map<String, String> readSkills(String directory) => {
  for (final skill in Directory(directory).listSync().whereType<Directory>())
    if (File(p.join(skill.path, 'SKILL.md')).existsSync())
      p.basename(skill.path): File(
        p.join(skill.path, 'SKILL.md'),
      ).readAsStringSync(),
};

/// Renders the generated library from skill files keyed by directory name.
///
/// The output is shaped so `dart format` leaves it unchanged. Throws a
/// [FormatException] for a skill whose front matter is missing, whose `name`
/// disagrees with its directory, or whose body cannot be a raw string.
String renderGuides(Map<String, String> skills) {
  final names = skills.keys.toList()..sort();
  final buffer = StringBuffer()
    ..writeln('// GENERATED by tool/generate_guides.dart — do not edit.')
    ..writeln('// Source of truth: skills/*/SKILL.md at the repository root.')
    ..writeln('// Regenerate: dart run tool/generate_guides.dart')
    ..writeln()
    ..writeln("part of 'guide.dart';")
    ..writeln()
    ..writeln('const _bundledGuides = <Guide>[');
  final bodies = <String, String>{};
  for (final name in names) {
    final skill = _parseSkill(name, skills[name]!);
    final constant = '_${_camel(name)}Body';
    bodies[constant] = skill.body;
    final description = _quote(skill.description);
    // dart format keeps a value beside its name only when the line fits.
    final descriptionLine = '    description: $description,';
    buffer
      ..writeln('  Guide(')
      ..writeln('    name: ${_quote(name)},')
      ..writeln(
        descriptionLine.length <= 80
            ? descriptionLine
            : '    description:\n        $description,',
      )
      ..writeln('    body: $constant,')
      ..writeln('  ),');
  }
  buffer.writeln('];');
  for (final MapEntry(key: constant, value: body) in bodies.entries) {
    buffer
      ..writeln()
      ..writeln("const $constant = r'''")
      ..write(body)
      ..writeln("''';");
  }
  return buffer.toString();
}

({String description, String body}) _parseSkill(String name, String source) {
  final match = RegExp(
    r'^---\n(.*?)\n---\n\n?(.*)$',
    dotAll: true,
  ).firstMatch(source);
  if (match == null) {
    throw FormatException('skills/$name/SKILL.md has no front matter');
  }
  final frontMatter = loadYaml(match.group(1)!);
  if (frontMatter is! Map ||
      frontMatter['name'] != name ||
      frontMatter['description'] is! String) {
    throw FormatException(
      'skills/$name/SKILL.md needs name: $name and a description',
    );
  }
  var body = match.group(2)!;
  if (body.contains("'''")) {
    throw FormatException("skills/$name/SKILL.md body contains '''");
  }
  if (!body.endsWith('\n')) body = '$body\n';
  return (description: frontMatter['description'] as String, body: body);
}

String _camel(String name) => name
    .split('-')
    .indexed
    .map(
      (part) => part.$1 == 0
          ? part.$2
          : '${part.$2[0].toUpperCase()}${part.$2.substring(1)}',
    )
    .join();

String _quote(String value) {
  final escaped = value
      .replaceAll(r'\', r'\\')
      .replaceAll("'", r"\'")
      .replaceAll(r'$', r'\$')
      .replaceAll('\n', r'\n');
  return "'$escaped'";
}
